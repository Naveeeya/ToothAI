#!/usr/bin/env python3
"""Build a Kaggle kernel that runs scripts/evaluate.py on the AKU validation/test splits.

    python photo_screening/scripts/build_eval_kernel.py && kaggle kernels push -p photo_screening/.smoke/eval_kernel

The AKU zip downloads quickly on Kaggle but slowly here. The kernel embeds a snapshot of the
pipeline code (the modules evaluate.py imports) and the calibrated thresholds, takes the trained
weights from the two training kernels' outputs (``kernel_sources``) and AlphaDent from its GitHub
release, then writes eval_results_aku.json and the raw-detection cache (re-scorable locally).
"""

from __future__ import annotations

import base64
import io
import json
import tarfile
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]
OUT = PKG / ".smoke" / "eval_kernel"
FILES = ["__init__.py", "app/__init__.py", "app/config.py", "app/schemas.py", "app/quality.py", "app/fusion.py",
         "app/imaging.py", "app/rules.py", "app/models/__init__.py", "app/models/base.py", "app/models/registry.py",
         "scripts/evaluate.py", "weights/caries_aku/thresholds.json", "weights/teeth_dentalai/thresholds.json"]


def snapshot() -> str:
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as tar:
        for f in FILES:
            tar.add(PKG / f, arcname=f"photo_screening/{f}")
    return base64.b64encode(buf.getvalue()).decode()


def cell(src: str, kind: str = "code") -> dict:
    c = {"cell_type": kind, "metadata": {}, "source": src.strip("\n")}
    if kind == "code":
        c.update(execution_count=None, outputs=[])
    return c


def main() -> None:
    blob = snapshot()
    cells = [
        cell("# ToothAI photo screening: AKU evaluation\n\nRuns `photo_screening/scripts/evaluate.py` on the AKU "
             "Benchmarking validation and test splits. Generated by `scripts/build_eval_kernel.py`.", "markdown"),
        cell('''
import subprocess, sys, os, glob, shutil, base64, io, tarfile, json, time, zipfile
from pathlib import Path
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "ultralytics>=8.3", "pydantic-settings>=2.3",
                "pillow-heif", "requests"], check=True)
W = Path("/kaggle/working"); SRC = Path("/tmp/src"); SRC.mkdir(exist_ok=True)
tarfile.open(fileobj=io.BytesIO(base64.b64decode(BLOB)), mode="r:gz").extractall(SRC, filter="data")
sys.path.insert(0, str(SRC))
weights = SRC / "photo_screening" / "weights"
for model_id, art in (("caries_aku", "caries_aku_artifacts"), ("teeth_dentalai", "teeth_dentalai_artifacts")):
    best = next(iter(glob.glob(f"/kaggle/input/**/{art}/best.pt", recursive=True)), None)
    print(model_id, "->", best)
    (weights / model_id).mkdir(parents=True, exist_ok=True)
    shutil.copy(best, weights / model_id / "best.pt")
'''.replace("BLOB", repr(blob))),
        cell('''
import requests
def download(url, dest, size):
    dest = Path(dest)
    while not dest.exists() or dest.stat().st_size < size:
        have = dest.stat().st_size if dest.exists() else 0
        with requests.get(url, headers={"Range": f"bytes={have}-"} if have else {}, stream=True, timeout=60) as r:
            with open(dest, "ab" if have else "wb") as f:
                for chunk in r.iter_content(8 << 20):
                    f.write(chunk)
    return dest
rel = requests.get("https://api.github.com/repos/ZFTurbo/AlphaDent/releases/tags/v1.0", timeout=60).json()
asset = next(a for a in rel["assets"] if a["name"] == "yolov8x_AlphaDent_4_classes_960px.pt")
(weights / "alphadent").mkdir(parents=True, exist_ok=True)
download(asset["browser_download_url"], weights / "alphadent" / asset["name"], asset["size"])
rec = requests.get("https://zenodo.org/api/records/14827784", timeout=60).json()
zf = next(f for f in rec["files"] if f["key"] == "Benchmarking Dataset.zip")
t = time.time(); z = download(zf["links"]["self"], "/tmp/aku.zip", zf["size"])
print(f"AKU zip in {time.time()-t:.0f} s")
with zipfile.ZipFile(z) as zz:
    zz.extractall("/tmp/aku", members=[n for n in zz.namelist() if "/train/" not in n])
root = next(Path("/tmp/aku").rglob("Benchmarking Dataset"))
print(root, [p.name for p in root.iterdir()])
'''),
        cell('''
os.environ["PHOTO_WEIGHTS_DIR"] = str(weights)
r = subprocess.run([sys.executable, str(SRC / "photo_screening/scripts/evaluate.py"), "--aku", str(root),
                    "--cache", str(W / "eval_cache"), "--out", str(W / "eval_results_aku.json")])
print("exit", r.returncode)
print(json.dumps(json.load(open(W / "eval_results_aku.json")), indent=1)[:6000])
'''),
    ]
    nb = {"cells": cells, "metadata": {"kernelspec": {"display_name": "Python 3", "language": "python",
                                                      "name": "python3"}, "accelerator": "GPU"},
          "nbformat": 4, "nbformat_minor": 5}
    for i, c in enumerate(nb["cells"]):
        c["id"] = f"e{i:02d}"
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "eval_aku.ipynb").write_text(json.dumps(nb, indent=1))
    (OUT / "kernel-metadata.json").write_text(json.dumps({
        "id": "alphaleporus/tooth-ai-photo-eval-aku", "title": "Tooth-AI photo eval AKU",
        "code_file": "eval_aku.ipynb", "language": "python", "kernel_type": "notebook", "is_private": True,
        "enable_gpu": True, "enable_tpu": False, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
        "dataset_sources": [], "competition_sources": [], "model_sources": [],
        "kernel_sources": ["alphaleporus/tooth-ai-photo-caries-aku", "alphaleporus/tooth-ai-photo-teeth-dentalai"],
    }, indent=2))
    print("wrote", OUT, f"(code snapshot {len(blob) // 1024} KB)")


if __name__ == "__main__":
    main()
